-- 0003_attendance.sql -- the days: punches, work-from-home, holidays.
--
-- One row per employee per attendance day. That single uniqueness rule is what makes
-- the offline queue safe to flush twice: the browser retries a punch it is unsure was
-- recorded, and the database's answer to a replay must be "already have it", not a
-- second arrival at work.

CREATE TABLE records (
  id                     uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id            uuid NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  attendance_day         date NOT NULL,

  check_in_at            timestamptz,
  check_out_at           timestamptz,

  -- Coordinates and accuracy are stored and the geofence is evaluated from them at
  -- read time, in M6, against the radius in `settings`. The browser's verdict is not
  -- accepted: it is the one thing an interested user can edit, and a radius change
  -- (office relocation, a fairer threshold for network-positioned phones) must apply
  -- to history rather than only to future punches.
  check_in_lat           double precision CHECK (check_in_lat  BETWEEN -90  AND 90),
  check_in_lng           double precision CHECK (check_in_lng  BETWEEN -180 AND 180),
  check_in_accuracy_m    numeric(8,2)     CHECK (check_in_accuracy_m >= 0),
  check_out_lat          double precision CHECK (check_out_lat BETWEEN -90  AND 90),
  check_out_lng          double precision CHECK (check_out_lng BETWEEN -180 AND 180),
  check_out_accuracy_m   numeric(8,2)     CHECK (check_out_accuracy_m >= 0),

  -- Punch photos. The retention job nulls these and sets photo_expired rather than
  -- deleting the row: the day still happened, and an expired selfie is a different
  -- fact from no selfie. Paths, never bytes -- a data: URI in a row makes every
  -- projection of every record list several hundred kilobytes.
  check_in_photo_path    text,
  check_out_photo_path   text,
  photo_expired          boolean NOT NULL DEFAULT false,

  -- 'punch' is a real arrival. The others are rows the rule engine materialises so the
  -- portal's day table still shows an approved leave or a regularised shift; they are
  -- written by the command path, not by a browser inventing a day.
  source                 text NOT NULL DEFAULT 'punch'
                         CHECK (source IN ('punch', 'leave', 'wfh', 'regularisation', 'import')),

  -- The idempotency key generated by the browser's offline queue. Nullable because
  -- materialised and imported rows have no queue entry; unique where present so a
  -- replayed flush cannot create a second row even across a day-key change.
  punch_id               uuid UNIQUE,

  -- Deliberately not a CHECK yet. The vocabulary of a displayed day ("Present",
  -- "Absent", "Leave", "WFH", "Loss of Pay", "Half Day", and the effective status the
  -- popover computes) is owned by the rule engine, and M5 is where it is extracted
  -- into lib/rules/*.ts with fixtures. A CHECK written now would be a second copy of
  -- that vocabulary, in the wrong place, free to disagree -- the exact failure mode
  -- this whole plan exists to avoid. 0006 adds the constraint once the rules are the
  -- single source.
  status                 text,
  location_type          text,
  biometric_verified     boolean,
  note                   text,

  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),

  UNIQUE (employee_id, attendance_day),
  -- A punch cannot end before it starts. Rollover across midnight is a *different*
  -- attendance_day, which is how M6 closes yesterday and opens today; it is not an
  -- out-of-order pair inside one row.
  CHECK (check_out_at IS NULL OR check_in_at IS NULL OR check_out_at >= check_in_at),
  -- Materialised rows are derived from another table; requiring their source row at
  -- the application layer is weaker than requiring a punch time here.
  CHECK (source <> 'punch' OR check_in_at IS NOT NULL)
);

CREATE INDEX records_employee_day_idx ON records (employee_id, attendance_day DESC);
CREATE INDEX records_day_idx ON records (attendance_day DESC);
-- The photo-cleanup job's query: find photos past their window without a full scan.
CREATE INDEX records_photo_pending_idx ON records (attendance_day)
  WHERE check_in_photo_path IS NOT NULL OR check_out_photo_path IS NOT NULL;

-- WFH is one request per employee per day, for the same reason records is: two approved
-- WFH rows for Tuesday is a bug nobody notices until the count is wrong.
CREATE TABLE wfh (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id  uuid NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  work_day     date NOT NULL,
  reason       text NOT NULL,
  plan         text,
  state        request_state NOT NULL DEFAULT 'Pending Manager',
  decided_by   uuid REFERENCES employees(id) ON DELETE SET NULL,
  decided_at   timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, work_day),
  CHECK (state NOT IN ('Approved', 'Rejected') OR (decided_by IS NOT NULL AND decided_at IS NOT NULL))
);

CREATE INDEX wfh_state_idx ON wfh (state) WHERE state IN ('Pending Manager', 'Pending Admin');
CREATE INDEX wfh_day_idx ON wfh (work_day);

-- Declared and Restricted are one table with a CHECK, not two tables or an untyped
-- text column, because the difference is load-bearing and already paid for:
-- getDeclaredHolidays() deliberately excludes Restricted Holidays from the holiday set
-- that suppresses LOP. Encoding it in the constraint means a row cannot be inserted
-- that quietly makes a restricted holiday behave like a declared one.
CREATE TABLE holidays (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- The portal's "HOL-01". Stable ids matter because a holiday id appears in export
  -- files; regenerating them on every projection would make an export non-reproducible.
  code          text NOT NULL UNIQUE,
  holiday_date  date NOT NULL,
  name          text NOT NULL,
  kind          text NOT NULL CHECK (kind IN ('declared', 'restricted')),
  -- Retired rather than deleted: a company holiday that stops being observed must keep
  -- explaining the attendance history of the day it fell on.
  active        boolean NOT NULL DEFAULT true,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (holiday_date, name)
);

CREATE INDEX holidays_date_idx ON holidays (holiday_date);

-- Worked-on-holiday overrides, per employee per day: the Admin/Manager exception that
-- turns a holiday that was worked into comp-off or extra pay. Its own table rather than
-- a settings blob because it is keyed by employee and day and must join against
-- holidays and records. The mode is constrained to exactly the two the portal offers.
CREATE TABLE holiday_work (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  employee_id  uuid NOT NULL REFERENCES employees(id) ON DELETE CASCADE,
  -- No foreign key: the thing being overridden is "the day this person worked", and a
  -- date is not unique in holidays (two observables can share one day), so there is no
  -- candidate key to point at. Retirement of a holiday must not silently delete the
  -- record that someone worked it, which an ON DELETE CASCADE would do.
  holiday_date date NOT NULL,
  mode         text NOT NULL CHECK (mode IN ('compoff', 'extrapay')),
  note         text,
  recorded_by  uuid REFERENCES employees(id) ON DELETE SET NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (employee_id, holiday_date)
);

DO $$
DECLARE t record;
BEGIN
  FOR t IN
    SELECT c.relname FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind = 'r'
       AND c.relname IN ('records', 'wfh', 'holidays', 'holiday_work')
  LOOP
    EXECUTE format(
      'CREATE TRIGGER %I BEFORE UPDATE ON %I FOR EACH ROW EXECUTE FUNCTION set_updated_at()',
      'set_updated_at_' || t.relname, t.relname);
  END LOOP;
END
$$;

COMMENT ON TABLE records IS
  'One row per employee per IST day. punch_id is the offline queue''s idempotency key.';
COMMENT ON COLUMN records.status IS
  'Owned by lib/rules (M5); unconstrained until that is the single source.';
COMMENT ON COLUMN holidays.kind IS
  'declared suppresses LOP; restricted does not. getDeclaredHolidays() depends on this.';
